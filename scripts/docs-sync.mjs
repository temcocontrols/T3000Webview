#!/usr/bin/env node
/**
 * docs-sync.mjs - the changelog ("What's New") pass.
 *
 *   node scripts/docs-sync.mjs --summarise [--since <ref>] [--limit N]
 *
 * Deterministic by design: it groups real commits by area and writes one page per day.
 * A model pass may later replace the bullets (the page says so); without a model the changelog
 * is still written, still correct, and never blocks anything.
 *
 * State: docs/help/changelog-ledger.json maps commit -> the page that consumed it, so re-running
 * never duplicates an entry.
 */
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const ROOT = process.cwd();
const argv = process.argv.slice(2);
const opt = (n, d = null) => {
  const i = argv.indexOf(n);
  return i >= 0 && argv[i + 1] ? argv[i + 1] : d;
};
const since = opt('--since');
const limit = opt('--limit', '50');
const LEDGER = path.join(ROOT, 'docs/help/changelog-ledger.json');
const OUT_DIR = path.join(ROOT, 'docs/t3000/releases/changelog');

const SCOPES = [
  ['Application', (f) => f.startsWith('src/')],
  ['Backend API', (f) => f.startsWith('api/')],
  ['Firmware / controllers', (f) => f.startsWith('T3000-Source/') || f.startsWith('t3net/')],
  ['Documentation', (f) => f.startsWith('docs/')],
  ['Build / tooling', (f) => f.startsWith('scripts/') || f === 'package.json' || f.startsWith('.github/')],
];

function git(args) {
  return execFileSync('git', args, { cwd: ROOT, encoding: 'utf8' });
}

if (!argv.includes('--summarise')) {
  console.log('docs-sync: nothing to do. Use --summarise to write the changelog, or --impact (phase 2).');
  process.exit(0);
}

const ledger = fs.existsSync(LEDGER) ? JSON.parse(fs.readFileSync(LEDGER, 'utf8')) : {};

const range = since ? `${since}..HEAD` : `-n ${limit}`;
const raw = git(['log', '--no-merges', '--name-only', '--format=%x01%H|%ad|%an|%s', '--date=short', ...(since ? [range] : ['-n', limit])]);

const commits = [];
for (const chunk of raw.split('\u0001').filter((c) => c.trim())) {
  const [head, ...fileLines] = chunk.trim().split(/\r?\n/);
  const [sha, date, author, ...subjectParts] = head.split('|');
  commits.push({
    sha,
    date,
    author,
    subject: subjectParts.join('|').trim(),
    files: fileLines.map((f) => f.trim()).filter(Boolean),
  });
}

const fresh = commits.filter((c) => c.sha && !ledger[c.sha]);
if (!fresh.length) {
  console.log(`docs-sync: ${commits.length} commit(s) scanned, all already in the changelog`);
  process.exit(0);
}

const today = new Date().toISOString().slice(0, 10);
const file = path.join(OUT_DIR, `${today}.md`);
const relFile = path.relative(ROOT, file).split(path.sep).join('/');

const grouped = new Map();
for (const c of fresh) {
  const scope = SCOPES.find(([, test]) => c.files.some(test));
  const key = scope ? scope[0] : 'Other';
  if (!grouped.has(key)) grouped.set(key, []);
  grouped.get(key).push(c);
}

const lines = [];
if (!fs.existsSync(file)) {
  lines.push(`# Changelog - ${today}`, '');
  lines.push('> Generated by `scripts/docs-sync.mjs` from the commit history. The bullet list is');
  lines.push('> deliberately mechanical (real commits, grouped by area); a review pass may rewrite the');
  lines.push('> wording before this page is announced.', '');
} else {
  lines.push('', `<!-- appended ${new Date().toISOString()} -->`, '');
}

for (const [scope, items] of [...grouped.entries()].sort()) {
  lines.push(`## ${scope}`, '');
  for (const c of items) {
    const areas = [...new Set(c.files.map((f) => (f.includes('/') ? f.split('/').slice(0, 2).join('/') : f)))].slice(0, 3);
    const suffix = areas.length ? ` _(${areas.join(', ')})_` : '';
    lines.push(`- \`${c.sha.slice(0, 7)}\` ${c.subject}${suffix}`);
  }
  lines.push('');
}

fs.mkdirSync(OUT_DIR, { recursive: true });
fs.appendFileSync(file, lines.join('\n'), 'utf8');

for (const c of fresh) ledger[c.sha] = relFile;
fs.mkdirSync(path.dirname(LEDGER), { recursive: true });
fs.writeFileSync(LEDGER, JSON.stringify(ledger, null, 2) + '\n', 'utf8');

console.log(`changelog: ${fresh.length} new commit(s) -> ${relFile}`);
for (const [scope, items] of [...grouped.entries()].sort()) console.log(`  ${scope}: ${items.length}`);
console.log(`ledger: ${Object.keys(ledger).length} commit(s) recorded`);
console.log('next: npm run docs:registry && npm run docs:site');
